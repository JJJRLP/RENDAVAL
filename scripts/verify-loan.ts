// node --env-file=.env.local --conditions=react-server --import tsx scripts/verify-loan.ts
// Only authentication is bypassed: these are the same helpers used by HTTP routes.
import assert from 'node:assert/strict';
import { Keypair, Operation, TransactionBuilder } from '@stellar/stellar-sdk';
import { required } from '../lib/server/env';
import { topup, buildRepayment, submitRepayment } from '../lib/server/loan/repayment';
import { settle } from '../lib/server/loan/settle';
import { attest } from '../lib/server/attestation';
import { register } from '../lib/server/loan/register';
import { accept } from '../lib/server/loan/accept';
import { buildDeposit, submitDeposit } from '../lib/server/loan/deposit';
import { disburse } from '../lib/server/loan/disburse';
import { escrowFor, state } from '../lib/server/loan/state';
import { bondAsset, dollarAsset, lenderKey, networkPassphrase, server, ProviderError } from '../lib/server/loan/network';
import { exampleBond } from '../lib/loan/model';
async function main() {
  const spikeWallet = 'GA4J2HFY45VDAX6T7YFMOXRAWXVX5RCQFI3Y6W6BM3NFW4T5LJ4VNYF4';
  const spikeAccount = await server.loadAccount(spikeWallet);
  const spike = { escrow: await escrowFor(spikeWallet), stage: spikeAccount.balances.some(b => 'asset_code' in b && b.asset_code === 'VBOND' && b.asset_issuer === bondAsset().getIssuer() && Number(b.balance) > 0) ? 'bond_registered' : 'none' };
  // This historical wallet has no KYB attestation. Inspect only public loan inputs; do not attest it.
  assert.ok(['none', 'bond_registered'].includes(spike.stage)); assert.equal(spike.escrow, null);
  console.log('spikeIgnored', { stage: spike.stage, escrow: spike.escrow });
  const company = Keypair.random(), wallet = company.publicKey();
  console.log('company', wallet);
  const issuer = Keypair.fromSecret(required('BOND_ISSUER_SECRET_KEY')).publicKey();
  console.log('issuerSubentriesBefore', (await server.loadAccount(issuer)).subentry_count);
  const funded = await fetch(`https://friendbot.stellar.org?addr=${wallet}`);
  assert.ok(funded.ok, 'Friendbot');
  const setup = new TransactionBuilder(await server.loadAccount(wallet), { fee: '10000', networkPassphrase }).addOperation(Operation.changeTrust({ asset: dollarAsset() })).addOperation(Operation.changeTrust({ asset: bondAsset() })).setTimeout(60).build();
  setup.sign(company); await server.submitTransaction(setup);
  console.log('attestation', await attest(wallet, `loan-test-${crypto.randomUUID()}`));
  const treasuryBefore = (await server.loadAccount(lenderKey().publicKey())).balances;
  console.log('treasuryBefore', treasuryBefore);
  console.log('register', await register(wallet, exampleBond));
  const registered = await state(wallet); assert.equal(registered.stage, 'bond_registered'); console.log('registered', registered);
  await assert.rejects(() => register(wallet, exampleBond), { status: 409 });
  const parallel = await Promise.allSettled([accept(wallet, exampleBond), accept(wallet, exampleBond)]);
  console.log('parallelAccept', parallel.map(p => p.status === 'fulfilled' ? p.value : { rejected: true, message: p.reason instanceof Error ? p.reason.message : 'error' }));
  const deployed = await accept(wallet, exampleBond); console.log('accept', deployed);
  await assert.rejects(() => disburse(wallet), { status: 409 });
  const wrong = new TransactionBuilder(await server.loadAccount(wallet), { fee: '10000', networkPassphrase }).addOperation(Operation.manageData({ name: 'not-a-deposit', value: 'test' })).setTimeout(60).build();
  wrong.sign(company);
  await assert.rejects(() => submitDeposit(wallet, wrong.toXDR()), { status: 400 });
  console.log('invalidDeposit', '400 refused');
  const reused = await accept(wallet, exampleBond); assert.equal(reused.contractId, deployed.contractId); console.log('acceptRepeated', reused);
  const roles = (await escrowFor(wallet))!.roles;
  assert.equal(roles.receiver, wallet); assert.notEqual(roles.serviceProvider, wallet); console.log('receiverOnlyRoles', roles);
  const built = await buildDeposit(wallet);
  const tx = TransactionBuilder.fromXDR(built.unsignedTransaction, networkPassphrase); tx.sign(company);
  console.log('deposit', await submitDeposit(wallet, tx.toXDR()));
  const locked = await state(wallet); assert.equal(locked.stage, 'collateral_locked'); console.log('locked', locked);
  console.log('parallelDisburse', await Promise.all([disburse(wallet), disburse(wallet)]));
  const active = await state(wallet); assert.equal(active.stage, 'active'); assert.equal(active.usdc, 200); console.log('active', active);
  const beforeRepeat = await server.loadAccount(lenderKey().publicKey());
  console.log('disburseRepeated', await disburse(wallet));
  const afterRepeat = await server.loadAccount(lenderKey().publicKey());
  assert.equal(afterRepeat.sequenceNumber(), beforeRepeat.sequenceNumber());
  assert.deepEqual(afterRepeat.balances, beforeRepeat.balances);
  assert.equal((await state(wallet)).usdc, active.usdc);
  await assert.rejects(() => buildDeposit(wallet), { status: 409 });
  console.log('secondDeposit', '409 refused');
  console.log('noSecondPayment', { sequenceUnchanged: true, companyUSDC: active.usdc, treasuryAfter: afterRepeat.balances });
  console.log('parallelTopup', await Promise.all([topup(wallet), topup(wallet)]));
  console.log('beforeRepayment', await state(wallet));
  const repaymentBuild = await buildRepayment(wallet);
  assert.equal(repaymentBuild.repaid, false);
  if (repaymentBuild.repaid) throw new Error('Unexpected repayment');
  const repayTx = TransactionBuilder.fromXDR(repaymentBuild.unsignedTransaction, networkPassphrase); repayTx.sign(company);
  await assert.rejects(() => submitRepayment(wallet, wrong.toXDR()), { status: 400 });
  console.log('repayment', await submitRepayment(wallet, repayTx.toXDR()));
  console.log('settle', await settle(wallet));
  const settled = await state(wallet);
  assert.ok(['repaid_release_pending', 'closed'].includes(settled.stage)); console.log('settled', settled);
  const onchain = await escrowFor(wallet, true);
  assert.equal(onchain?.milestones[0].status, 'completed'); assert.equal(onchain?.milestones[0].approved, true);
  console.log('onchain', onchain);
  const beforeRetries = await server.loadAccount(lenderKey().publicKey());
  console.log('repeatTopup', await topup(wallet));
  console.log('repeatBuild', await buildRepayment(wallet));
  console.log('repeatSubmit', await submitRepayment(wallet, repayTx.toXDR()));
  console.log('repeatSettle', await settle(wallet));
  const afterRetries = await server.loadAccount(lenderKey().publicKey());
  assert.equal(beforeRetries.sequenceNumber(), afterRetries.sequenceNumber()); assert.deepEqual(beforeRetries.balances, afterRetries.balances);
  const usdc = (balances: typeof treasuryBefore) => Number(balances.find(b => 'asset_code' in b && b.asset_code === 'USDC' && b.asset_issuer === dollarAsset().getIssuer())?.balance ?? 0);
  assert.ok(Math.abs(usdc(afterRetries.balances) - usdc(treasuryBefore)) < 0.0000001);
  assert.equal((await server.loadAccount(issuer)).subentry_count, 0);
  console.log('finalProof', { retriesChangedNothing: true, issuerSubentriesAfter: 0, lenderUSDCBefore: usdc(treasuryBefore), lenderUSDCAfter: usdc(afterRetries.balances), company: await state(wallet) });
}
main().catch(error => { console.error(error instanceof ProviderError ? JSON.stringify({ providerStatus: error.providerStatus, detail: error.detail }) : error instanceof Error ? error.message : 'Verification failed'); process.exitCode = 1; });
